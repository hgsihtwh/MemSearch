rows = {r["№"]: r for r in csv.DictReader(open(PASSPORT, encoding="utf-8-sig"))}
items = [
    (
        q,
        kind,
        where,
        ans,
        basis,
        "Claude (черновик)",
        "да" if basis.startswith("транскрипт") else "",
    )
    for q, kind, where, ans, basis in Q
]
for n, qs in MANUAL.items():
    where = "речь" if rows[str(n)]["Речь"] == "да" else "текст"
    for q in qs:
        q, extra = (
            q if isinstance(q, tuple) else (q, [])
        )  # extra — другие ролики, которые тоже подходят
        items.append(
            (
                q,
                "перефраз" if not extra else "тема",
                where,
                [n] + extra,
                "Анастасия, после просмотра ролика",
                "Анастасия",
                "да",
            )
        )
for it in items:
    for n in it[3]:
        assert str(n) in rows, n
# группируем по ролику, запросы без ответа — в конце
items.sort(key=lambda it: (not it[3], it[3][0] if it[3] else 0, it[5] != "Анастасия"))

HEAD = [
    "№",
    "Запрос",
    "Вид запроса",
    "Где ответ в ролике",
    "Правильные ролики (№ по паспорту)",
    "Ссылки",
    "Основание",
    "Автор запроса",
    "Проверено",
    "Комментарий",
]
out = [
    [
        i,
        q,
        kind,
        where,
        ", ".join(map(str, ans)),
        "\n".join(rows[str(n)]["Ссылка"] for n in ans),
        basis,
        author,
        checked,
        "",
    ]
    for i, (q, kind, where, ans, basis, author, checked) in enumerate(items, 1)
]
Q = items

with open(os.path.join(HERE, "control_queries.csv"), "w", encoding="utf-8-sig", newline="") as f:
    w = csv.writer(f)
    w.writerow(HEAD)
    w.writerows(out)

wb = Workbook()
ws = wb.active
ws.title = "Запросы"
ws.append(HEAD)
for r in out:
    ws.append(r)
thin = Side(style="thin", color="BBBBBB")
for c in ws[1]:
    c.font = Font(bold=True)
    c.fill = PatternFill("solid", fgColor="DDEBF7")
for row in ws.iter_rows():
    for c in row:
        c.alignment = Alignment(wrap_text=True, vertical="top")
        c.border = Border(top=thin, bottom=thin, left=thin, right=thin)
for col, wd in zip("ABCDEFGHIJ", [5, 48, 13, 14, 16, 50, 32, 16, 11, 30], strict=True):
    ws.column_dimensions[col].width = wd
ws.freeze_panes = "C2"
ws.auto_filter.ref = ws.dimensions
dv = DataValidation(type="list", formula1='"да,нет,исправить"', allow_blank=True)
ws.add_data_validation(dv)
dv.add(f"I2:I{len(out) + 1}")

s = wb.create_sheet("Сводка")
n = len(out) + 1
s.append(["Показатель", "Значение"])
s.append(["Всего запросов", f"=COUNTA(Запросы!B2:B{n})"])
for k in ["перефраз", "тема", "без ответа"]:
    s.append([f"Вид: {k}", f'=COUNTIF(Запросы!C2:C{n},"{k}")'])
for k in ["речь", "текст", "изображение"]:
    s.append([f"Где ответ: {k}", f'=COUNTIF(Запросы!D2:D{n},"{k}")'])
s.append(["Автор: Анастасия", f'=COUNTIF(Запросы!H2:H{n},"Анастасия")'])
s.append(["Проверено («да»)", f'=COUNTIF(Запросы!I2:I{n},"да")'])
s.append(["Роликов коллекции задействовано", len({a for q in Q for a in q[3]})])
for c in s[1]:
    c.font = Font(bold=True)
s.column_dimensions["A"].width = 34
s.column_dimensions["B"].width = 12
wb.save(os.path.join(HERE, "control_queries.xlsx"))

